import { Entity, PrimaryColumn, Column, CreateDateColumn, UpdateDateColumn, ManyToOne, JoinColumn, Index, Check } from 'typeorm';
import { Vault } from '../../vault/entities/vault.entity';
import { User } from '../../user/entities/user.entity';
import { AlbumKind } from '../../../common/types';

@Entity('albums')
@Index('idx_albums_vault', ['vaultId'])
@Index('uq_albums_liked_owner_vault', ['ownerUserId', 'vaultId'], { unique: true, where: "kind = 'liked'" })
@Check(
  'chk_albums_kind',
  "(kind = 'regular' AND name_encrypted IS NOT NULL AND name_nonce IS NOT NULL AND key_wrapped IS NOT NULL AND key_nonce IS NOT NULL) " +
    "OR (kind = 'liked' AND owner_user_id IS NOT NULL)",
)
export class Album {
  /** Generated by the client for a regular album (its key and name are bound to it), by the server for Liked. */
  @PrimaryColumn('uuid')
  id: string;

  @Column({ name: 'vault_id', type: 'uuid' })
  vaultId: string;

  @ManyToOne(() => Vault, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'vault_id' })
  vault: Vault;

  @Column({ type: 'enum', enum: AlbumKind, default: AlbumKind.REGULAR })
  kind: AlbumKind;

  /**
   * Null for regular albums. Set for per-user albums (the Liked album),
   * visible only to that user.
   */
  @Column({ name: 'owner_user_id', type: 'uuid', nullable: true })
  ownerUserId: string | null;

  @ManyToOne(() => User, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'owner_user_id' })
  ownerUser: User | null;

  /** Album name encrypted under the album key. Null for the Liked album, which clients label themselves. */
  @Column({ name: 'name_encrypted', type: 'text', nullable: true })
  nameEncrypted: string | null;

  @Column({ name: 'name_nonce', type: 'text', nullable: true })
  nameNonce: string | null;

  /** The album key wrapped under the vault key, so every vault member can open every album. Null for Liked. */
  @Column({ name: 'key_wrapped', type: 'text', nullable: true })
  keyWrapped: string | null;

  @Column({ name: 'key_nonce', type: 'text', nullable: true })
  keyNonce: string | null;

  @Column({ name: 'cover_media_id', type: 'uuid', nullable: true })
  coverMediaId: string | null;

  @Column({ name: 'sort_order', type: 'int', default: 0 })
  sortOrder: number;

  @Column({ name: 'media_count', type: 'int', default: 0 })
  mediaCount: number;

  @Column({ name: 'created_by', type: 'uuid', nullable: true })
  createdBy: string | null;

  @ManyToOne(() => User, { onDelete: 'SET NULL' })
  @JoinColumn({ name: 'created_by' })
  creator: User | null;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt: Date;
}
