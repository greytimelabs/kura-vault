export type Bytes = Uint8Array<ArrayBuffer>;

export function b64decode(value: string): Bytes {
  const binary = atob(value);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) out[i] = binary.charCodeAt(i);
  return out;
}

export function b64encode(bytes: Uint8Array): string {
  let binary = '';
  const chunk = 0x8000;
  for (let i = 0; i < bytes.length; i += chunk) {
    binary += String.fromCharCode(...bytes.subarray(i, i + chunk));
  }
  return btoa(binary);
}

export function hexEncode(bytes: Uint8Array): string {
  let out = '';
  for (const b of bytes) out += b.toString(16).padStart(2, '0');
  return out;
}

export function hexDecode(hex: string): Bytes {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
}

export function utf8Encode(text: string): Bytes {
  return new TextEncoder().encode(text) as Bytes;
}

export function utf8Decode(bytes: Uint8Array): string {
  // fatal: a wrong key that slips past nothing should still never yield garbage text
  return new TextDecoder('utf-8', { fatal: true }).decode(bytes);
}
